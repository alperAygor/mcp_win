#!/usr/bin/env python3
"""Generates hash-pinned lock files (build/locks/*.txt) for every Python MCP, resolved for Windows x64 / CPython 3.12.

Why: the installer and every downloadable pack install ONLY exact, hash-verified wheels (pip --require-hashes --no-deps),
so what ships is byte-for-byte what was reviewed - no surprise upgrades, no dependency resolution on the user's PC.

Resolution happens on any OS (pip's --platform flags), but environment markers would be evaluated for the *host*
(e.g. `colorama; sys_platform == "win32"` would be dropped on macOS/Linux). A second pass evaluates every locked
package's markers for Windows and adds anything missing, repeating until stable.

usage: python build/lock_packs.py [--python <venv python>] [id ...]     (ids: pack ids and/or "core")
"""
import json, subprocess, sys, tempfile, os
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCKS = ROOT / "build" / "locks"
sys.path.insert(0, "")
try:
    from pip._vendor.packaging.markers import Marker, default_environment
    from pip._vendor.packaging.requirements import Requirement
    from pip._vendor.packaging.utils import canonicalize_name
except Exception as e:  # pragma: no cover
    sys.exit(f"needs a venv with a recent pip (pip._vendor.packaging): {e}")

WIN_ENV = {**default_environment(), "sys_platform": "win32", "platform_system": "Windows", "os_name": "nt",
           "platform_machine": "AMD64", "platform_release": "10", "python_version": "3.12", "python_full_version": "3.12.15",
           "implementation_name": "cpython", "platform_python_implementation": "CPython", "extra": ""}
HOST_ENV = {**default_environment(), "extra": ""}


def resolve(specs: list[str]) -> list[dict]:
    with tempfile.TemporaryDirectory() as td:
        report = Path(td) / "report.json"
        cmd = [sys.executable, "-m", "pip", "install", "--dry-run", "--quiet", "--ignore-installed", "--ignore-requires-python",
               "--only-binary=:all:", "--platform", "win_amd64", "--implementation", "cp", "--python-version", "3.12",
               "--target", str(Path(td) / "t"), "--report", str(report), *specs]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0:
            raise SystemExit(f"pip could not resolve {specs}:\n{r.stderr[-1500:]}")
        return json.loads(report.read_text())["install"]


def windows_only_missing(entries: list[dict]) -> list[str]:
    have = {canonicalize_name(e["metadata"]["name"]) for e in entries}
    missing = []
    for e in entries:
        for line in e["metadata"].get("requires_dist", []) or []:
            req = Requirement(line)
            if not req.marker or "extra" in str(req.marker):
                continue
            on_win, on_host = req.marker.evaluate(WIN_ENV), req.marker.evaluate(HOST_ENV)
            if on_win and not on_host and canonicalize_name(req.name) not in have:
                missing.append(req.name)
    return sorted(set(missing))


def lock(specs: list[str], skip: set[str] = frozenset()) -> tuple[list[dict], list[str]]:
    specs = list(specs)
    added: list[str] = []
    for _ in range(5):
        entries = resolve(specs)
        miss = windows_only_missing(entries)
        if not miss:
            break
        added += miss
        specs += miss
    else:
        raise SystemExit("windows-marker pass did not converge")
    out = []
    for e in entries:
        name = canonicalize_name(e["metadata"]["name"])
        if name in skip:
            continue
        h = e["download_info"]["archive_info"]["hashes"]["sha256"]
        out.append({"name": name, "version": e["metadata"]["version"], "sha256": h})
    return sorted(out, key=lambda x: x["name"]), added


def pypi_wheel(name: str, version: str) -> dict:
    """Hash of the pure-Python wheel of name==version straight from PyPI (for no-deps extras)."""
    import urllib.request
    data = json.load(urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json"))
    wheels = [u for u in data["urls"] if u["packagetype"] == "bdist_wheel" and u["filename"].endswith("-py3-none-any.whl")]
    if not wheels:
        raise SystemExit(f"no py3-none-any wheel for {name}=={version}")
    return {"name": canonicalize_name(name), "version": version, "sha256": wheels[0]["digests"]["sha256"]}


def write_lock(path: Path, title: str, specs: list[str], entries: list[dict], added: list[str]) -> None:
    lines = [f"# {title}", "# generated by build/lock_packs.py - Windows x64, CPython 3.12, wheels only. DO NOT EDIT BY HAND.",
             f"# requested: {' '.join(specs)}"]
    if added:
        lines.append(f"# windows-only dependencies added by the marker pass: {' '.join(added)}")
    for e in entries:
        lines.append(f"{e['name']}=={e['version']} --hash=sha256:{e['sha256']}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    wanted = [a for a in sys.argv[1:] if not a.startswith("--")]
    LOCKS.mkdir(parents=True, exist_ok=True)
    packs = json.loads((ROOT / "build" / "packs.json").read_text())
    versions = json.loads((ROOT / "versions.json").read_text())
    jobs = {}
    jobs["core-python"] = ([*versions["python"]["shared"], *[i["spec"] for i in versions["python"]["isolated"].values()]], "core (installer-bundled) Python MCPs")
    for pid, p in packs.items():
        if p["runtime"] == "python":
            jobs[pid] = (p["pip"], f"pack {pid}")
    for key, (specs, title) in jobs.items():
        if wanted and key not in wanted and not (key == "core-python" and "core" in wanted):
            continue
        local = packs.get(key, {}).get("local")
        # a local package (ours) is installed separately with --no-deps; its own requirements are what we lock
        entries, added = lock(specs)
        entries = [e for e in entries if not (local and e["name"] == "archmcp-opensees")]
        for extra in packs.get(key, {}).get("noDepsExtra", []):
            entries.append(pypi_wheel(*extra.split("==")))
        entries.sort(key=lambda x: x["name"])
        write_lock(LOCKS / f"{key}.txt", title, specs, entries, added)
        print(f"{key:12s} {len(entries):3d} packages" + (f"  (+windows-only: {', '.join(added)})" if added else ""))


if __name__ == "__main__":
    main()
